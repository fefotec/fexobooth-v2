def apply_locale_to_config(config: Dict[str, Any]) -> Dict[str, Any]:
    """Normalize locale and update legacy ui_texts used by older screens."""
    locale = get_locale(config)
    config["locale"] = locale

    ui_texts = deepcopy(config.get("ui_texts", {}))
    ui_texts.update({
        "start": t(locale, "common.start"),
        "finish": t(locale, "common.finish"),
        "print": t(locale, "common.print"),
        "redo": t(locale, "common.redo"),
        "cancel": t(locale, "common.cancel"),
        "choose_mode": t(locale, "start.choose_mode"),
        "choose_filter": t(locale, "filter.choose_style"),
    })
    config["ui_texts"] = ui_texts
    return config


